import assert from 'node:assert/strict';
const helpers=await import('../src/collectionStatus.ts').catch(()=>null);
assert.ok(helpers,'explicit collection-status helpers must exist');
const { ownershipPatch, makeStatusUndo, applyStatusUndo, listenedPatch }=helpers;
assert.deepEqual(ownershipPatch('want'),{owned:false,wantlist:true});
assert.deepEqual(ownershipPatch('owned'),{owned:true,wantlist:false});
assert.deepEqual(ownershipPatch('none'),{owned:false,wantlist:false});
const before={owned:true,notes:'old',rating:4};
const patch=ownershipPatch('want');
const undo=makeStatusUndo('album-a',before,patch);
assert.ok(undo);
const changed={...before,...patch,notes:'newer note',rating:5};
assert.deepEqual(applyStatusUndo(changed,undo),{owned:true,notes:'newer note',rating:5});
assert.deepEqual(before,{owned:true,notes:'old',rating:4},'input unchanged');
const stale={...changed,owned:true};
assert.equal(applyStatusUndo(stale,undo),stale,'stale undo is rejected without overwriting newer status');
assert.equal(makeStatusUndo('album-a',before,{notes:'new'}),null,'collector edit is not a status undo');
const listened=listenedPatch({},'2026-09-10T00:00:00Z');
assert.deepEqual(listened,{listened:true,lastListened:'2026-09-10T00:00:00Z'});
const undoListen=makeStatusUndo('album-a',{},listened);
assert.deepEqual(applyStatusUndo({...listened,shelfLocation:'A'},undoListen),{shelfLocation:'A'});
assert.deepEqual(listenedPatch({listened:true,lastListened:'earlier'},'now'),{listened:false,lastListened:'earlier'});
console.log('Explicit collection status and scoped undo tests passed');
